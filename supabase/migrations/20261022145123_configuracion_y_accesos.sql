-- Fase 1: configuración y lectura del panel. No cambia el proveedor activo.
-- Aplicar en un proyecto Supabase de desarrollo vacío, nunca sobre Airtable.
begin;

create table public.restaurantes (
  id bigint generated by default as identity primary key,
  airtable_record_id text unique,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  nombre text not null check (length(trim(nombre)) > 0),
  zona_horaria text not null default 'Europe/Madrid',
  duracion_reserva_minutos integer not null check (duracion_reserva_minutos between 1 and 1440),
  antelacion_minima_reserva_minutos integer not null default 30
    check (antelacion_minima_reserva_minutos >= 0),
  creado_en timestamptz not null default now()
);

create table public.restaurante_usuarios (
  restaurante_id bigint not null references public.restaurantes(id),
  usuario_id uuid not null references auth.users(id) on delete cascade,
  rol text not null check (rol in ('propietario', 'encargado', 'empleado')),
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  primary key (restaurante_id, usuario_id)
);
create index restaurante_usuarios_por_usuario
  on public.restaurante_usuarios(usuario_id, restaurante_id) where activo;

create table public.zonas (
  id uuid primary key default gen_random_uuid(),
  restaurante_id bigint not null references public.restaurantes(id),
  airtable_record_id text unique,
  nombre text not null check (length(trim(nombre)) > 0),
  estado text not null default 'activo' check (estado in ('activo', 'inactivo')),
  unique (restaurante_id, id)
);
create index zonas_por_restaurante on public.zonas(restaurante_id);

create table public.mesas (
  id uuid primary key default gen_random_uuid(),
  restaurante_id bigint not null references public.restaurantes(id),
  zona_id uuid not null,
  airtable_record_id text unique,
  nombre text not null check (length(trim(nombre)) > 0),
  capacidad integer not null check (capacidad > 0),
  min_personas integer not null default 1 check (min_personas > 0),
  estado text not null default 'libre' check (estado in ('libre', 'fuera de servicio')),
  check (min_personas <= capacidad),
  unique (restaurante_id, id),
  foreign key (restaurante_id, zona_id) references public.zonas(restaurante_id, id)
);
create index mesas_por_zona on public.mesas(restaurante_id, zona_id);

-- SECURITY DEFINER evita recursión de RLS sobre la tabla de pertenencias.
-- Devuelve únicamente un booleano, siempre para el usuario autenticado actual.
create schema if not exists contactia_privado;
revoke all on schema contactia_privado from public, anon, authenticated;
grant usage on schema contactia_privado to authenticated;
create function contactia_privado.es_miembro(restaurante bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.restaurante_usuarios ru
    where ru.restaurante_id = restaurante
      and ru.usuario_id = (select auth.uid()) and ru.activo
  );
$$;
revoke all on function contactia_privado.es_miembro(bigint) from public, anon;
grant execute on function contactia_privado.es_miembro(bigint) to authenticated;

alter table public.restaurantes enable row level security;
alter table public.restaurante_usuarios enable row level security;
alter table public.zonas enable row level security;
alter table public.mesas enable row level security;

-- No se permite acceso anónimo ni escrituras del panel en esta fase.
-- Evita también permisos automáticos heredados de Supabase.
revoke all on public.restaurantes, public.restaurante_usuarios,
  public.zonas, public.mesas from public, anon, authenticated;
grant select on public.restaurantes, public.restaurante_usuarios,
  public.zonas, public.mesas to authenticated;
grant all on public.restaurantes, public.restaurante_usuarios,
  public.zonas, public.mesas to service_role;
revoke all on sequence public.restaurantes_id_seq from public, anon, authenticated;
grant usage, select on sequence public.restaurantes_id_seq to service_role;

create policy leer_restaurante_propio on public.restaurantes for select to authenticated
  using (contactia_privado.es_miembro(id));
create policy leer_pertenencia_propia on public.restaurante_usuarios for select to authenticated
  using (usuario_id = (select auth.uid()) and activo);
create policy leer_zonas_propias on public.zonas for select to authenticated
  using (contactia_privado.es_miembro(restaurante_id));
create policy leer_mesas_propias on public.mesas for select to authenticated
  using (contactia_privado.es_miembro(restaurante_id));

comment on table public.restaurante_usuarios is
  'Altas y cambios de rol solo desde administración de servidor. Nunca desde metadatos editables del usuario.';
comment on table public.restaurantes is
  'No almacenar claves API ni contraseñas. Los usuarios pertenecen a auth.users.';
commit;
